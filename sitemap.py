# Function to extract latitude and longitude info
#
def place_location(pagetitle, page_text):

  numbers = []
  location_match = re.search(r'\{\{#display_map:(.+?)}\}', page_text, flags=re.IGNORECASE | re.DOTALL)
  outfile.write(str(location_match) + "\n")
  while location_match:
    location_text = location_match.group(1)
    float_pattern = r'[-+]?\d*\.\d+'
    floats = re.findall(float_pattern, location_text)
    # Convert to float type and return the first two found
    latlong = [float(f) for f in floats[:2]]
    if len(latlong) == 2:
      outfile.write(f"Page: {pagetitle} latitude {latlong[0]:f} longitude {latlong[1]:f} \n")   
      numbers += [(latlong[0],latlong[1])]
    else:
      error_string = f"Invalid location at page: {pagetitle}: {location_text}"
      outfile.write(error_string + "\n")
    page_text = page_text[location_match.end():]  # remove text already done
    location_match = re.search(r'\{\{#display_map:(.+?)}\}', page_text, flags=re.IGNORECASE | re.DOTALL)   

  return numbers 



# 
def displaytitle(text):
  instance = re.search(r'{{DISPLAYTITLE:(.*?)}}', text[0:200])  #  Only look in first 200 characters
  if instance:
    output_text = instance.group(1)
  else:
    output_text = ""
  output_text = re.sub("%27","'",output_text)   # convert single quote characters
  output_text = re.sub("&amp;","&",output_text) # convert & characters  
  return  output_text


#=====================================================================================================
#
# function to replace white space and %20 characters in a filename string with underscore characters
# 
# 
def replace_underscore(text):
    text = re.sub(r'&amp;','&', text)
    text = re.sub(r'\s+$', '', text)
    text = re.sub(r'\s', '_', text)
    text = re.sub(r'__','_',text)
    text = text.lstrip('_')
    text = re.sub(r'%20', '_', text)
    text = re.sub(r'%27', '\'', text)   # some files have %27 instead of a single quote character (apostrophe)
    return(text)

